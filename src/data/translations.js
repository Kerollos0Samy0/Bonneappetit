/**
 * Returns a product object adapted to the current language.
 */
export function getLocalizedProduct(product, lang = 'ar') {
  if (!product) return product;
  if (lang === 'en' && PRODUCT_TRANSLATIONS_EN[product.id]) {
    const t = PRODUCT_TRANSLATIONS_EN[product.id];
    return {
      ...product,
      name: t.name || product.name,
      unit: t.unit || product.unit,
      description: t.description || product.description
    };
  }
  return product;
}
